first_number = int(input("What is the first number? "))
second_number = int(input("What is the second number? "))

sum = first_number + second_number
difference = first_number - second_number
product = first_number * second_number
quotient = first_number / second_number
whole_number_division = first_number // second_number
rest = first_number % second_number

print(f"Sum of the two numbers are: {sum}")
print(f"Difference between two numbers are: {difference}")
print(f"Product of the two numbers are: {product}")
print(f"Quotient of the two numbers are: {quotient}")
print(f"Whole number division of the two numbers give: {whole_number_division}")
print(f"The rest after division is: {rest}")
